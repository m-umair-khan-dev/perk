#!/usr/bin/env bash
# Entry point of the dev container. Usage (from the host):
#   docker compose run --rm dev <command>
set -euo pipefail

cd /work
WIN_TARGET=x86_64-pc-windows-gnu
DIST=/work/dist
VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n1)

build_linux()   { cargo build --release --locked; }
build_windows() { cargo build --release --locked --target "$WIN_TARGET"; }

package_linux() {
    build_linux
    mkdir -p "$DIST"
    cargo deb --no-build --no-strip -o "$DIST/"
    local stage
    stage=$(mktemp -d)/perk-$VERSION-linux-x86_64
    mkdir -p "$stage"
    install -m755 "$CARGO_TARGET_DIR/release/perk" "$stage/perk"
    install -m644 packaging/linux/perk.desktop packaging/linux/perk.svg README.md LICENSE "$stage/"
    tar -C "$(dirname "$stage")" -czf "$DIST/perk-$VERSION-linux-x86_64.tar.gz" "$(basename "$stage")"
    cargo generate-rpm --target-dir "$CARGO_TARGET_DIR" -o "$DIST/"
}

package_windows() {
    build_windows
    mkdir -p "$DIST"
    local exe="$CARGO_TARGET_DIR/$WIN_TARGET/release/perk.exe"
    local stage
    stage=$(mktemp -d)
    cp "$exe" README.md LICENSE "$stage/"
    (cd "$stage" && zip -q -9 "$DIST/perk-$VERSION-windows-x86_64.zip" perk.exe README.md LICENSE)
    # App icon generated by build.rs (same renderer as the tray icons).
    local icon
    icon=$(ls -t "$CARGO_TARGET_DIR"/$WIN_TARGET/release/build/perk-*/out/perk.ico | head -n1)
    makensis -V2 -DVERSION="$VERSION" -DEXE="$exe" -DICON="$icon" -DOUTFILE="$DIST/perk-$VERSION-windows-x86_64-setup.exe" \
        packaging/windows/installer.nsi
}

cmd=${1:-help}
shift || true
case "$cmd" in
    build)           build_linux; build_windows ;;
    build-linux)     build_linux ;;
    build-windows)   build_windows ;;
    test)            cargo test --locked "$@" ;;
    lint)
        cargo fmt --all -- --check
        cargo clippy --locked --all-targets -- -D warnings
        cargo clippy --locked --all-targets --target "$WIN_TARGET" -- -D warnings ;;
    fmt)             cargo fmt --all ;;
    check)           "$0" lint; "$0" test ;;
    package)         package_linux; package_windows; ls -lh "$DIST" ;;
    package-linux)   package_linux ;;
    package-windows) package_windows ;;
    clean)           cargo clean; rm -rf "$DIST" ;;
    cargo)           cargo "$@" ;;
    shell)           exec bash ;;
    help|*)
        cat <<EOF
Perk dev container. Usage: docker compose run --rm dev <command>

  build            Release build for Linux and Windows
  build-linux      Release build for Linux only
  build-windows    Release build for Windows only (cross-compiled)
  test [args]      Run the test suite
  lint             rustfmt check + clippy for both targets
  fmt              Format the code
  check            lint + test
  package          Build all packages into ./dist
  package-linux    .deb + .rpm + .tar.gz into ./dist
  package-windows  .zip + NSIS installer into ./dist
  cargo <args>     Run any cargo command
  shell            Interactive shell
  clean            Remove build output and ./dist
EOF
        ;;
esac
